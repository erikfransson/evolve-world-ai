// Assembles the WAT kernels in src/sim/wasm/ into the text of kernels.generated.ts (base64 modules).
import { readFileSync } from "node:fs";
import wabtInit from "wabt";
import { LAYOUT } from "../src/sim/wasm/layout.ts";
import { expandTemplates } from "./watTemplate.ts";

const dir = new URL("../src/sim/wasm/", import.meta.url);
const kernels = { BRAIN: "brain.wat", SENSE: "sense.wat", FILL: "fill.wat", STEP: "step.wat", CROWD: "crowd.wat", MEMBERS: "members.wat" };

// {{NAME}} in a .wat file becomes LAYOUT.NAME (the row and call block offsets shared with the TypeScript).
const withLayout = (text: string, file: string): string =>
  text.replace(/\{\{(\w+)\}\}/g, (_, name: string) => {
    const v = (LAYOUT as Record<string, number>)[name];
    if (v === undefined) throw new Error(`${file}: no layout offset ${name}`);
    return String(v);
  });

// The .wat text as assembled: templates expanded, then the layout offsets substituted.
export const watText = (file: string): string =>
  withLayout(expandTemplates(readFileSync(new URL(file, dir), "utf8"), file, (name) => name in LAYOUT), file);

export async function generatedSource(): Promise<string> {
  const wabt = await wabtInit();
  let text = "// Generated by `npm run wasm` from the .wat files next to this one. Do not edit.\n";
  for (const [name, file] of Object.entries(kernels)) {
    const { buffer } = wabt.parseWat(file, watText(file), { simd: true }).toBinary({});
    text += `export const ${name}_WASM_BASE64 =\n  "${Buffer.from(buffer).toString("base64")}";\n`;
  }
  return text;
}
